import numpy as np

a = np.array([[10, 20], [30, 40]])
b = np.array([[2, 4], [5, 8]])

print("First Array:")
print(a)

print("Second Array:")
print(b)

print("Addition:")
print(np.add(a, b))

print("Subtraction:")
print(np.subtract(a, b))

print("Multiplication:")
print(np.multiply(a, b))

print("Division:")
print(np.divide(a, b))

print("Transpose:")
print(np.transpose(a))

print("Exponential:")
print(np.exp(a))